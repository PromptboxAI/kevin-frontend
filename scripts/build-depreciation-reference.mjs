/**
 * Generate the public useful-life reference from the LIVE schedule.
 *
 *   node scripts/build-depreciation-reference.mjs            # write
 *   node scripts/build-depreciation-reference.mjs --check    # verify, exit 1 if stale
 *
 * WHY THIS IS GENERATED AND NOT TYPED. Domain rule 13 is explicit: the live
 * source is `GET /v1/depreciation-rules`, "fetch not retype". A hand-kept copy
 * of 87 schedule lines would be wrong within a release and nothing would fail
 * to say so -- the same failure mode as the docs exports, which drifted in
 * three places before they were generated.
 *
 * It also replaces a worse idea. A PDF was offered as a downloadable
 * depreciation schedule; it turned out to be a DEVELOPER SPEC (platform field
 * list, calculation_type, manual_review_required) wrapped around an
 * alphabetical item table -- Brick-a-brac, Briefcases, Broilers -- which is not
 * the structure the engine runs. Publishing it would have contradicted the
 * "31 categories, 87 sub-lines" figure on six pages and handed over the
 * taxonomy. This publishes what the product actually applies.
 *
 * WHAT IS DELIBERATELY NOT PUBLISHED: pcs_code, source_group and boundary.
 * Those are mapping and routing internals. The reference answers one question
 * -- how long is this class expected to last, and how does it depreciate --
 * which is what an adjuster is checking and what the schedule is judged on.
 */
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const TS_OUT = join(root, 'src/content/depreciation-schedule.generated.ts')
const CSV_OUT = join(root, 'public/reference/kevin-useful-life-schedule.csv')

const check = process.argv.includes('--check')

/** Plain English for the engine's `mode`. The reader is an adjuster, not an integrator. */
const MODE_LABEL = {
  age_based: 'Straight line by age',
  flat_rate: 'Flat rate',
  replacement_cost: 'Percentage of replacement cost',
  never: 'Does not depreciate',
  manual: 'Valued manually',
}

async function base() {
  // The generator runs outside Vite, so read the env file rather than import.meta.
  const env = await readFile(join(root, '.env.local'), 'utf8').catch(() => '')
  const m = env.match(/^VITE_API_BASE_URL=(.*)$/m)
  const raw = (m ? m[1] : '').trim().replace(/^['"]|['"]$/g, '').replace(/\/$/, '')
  if (!raw) throw new Error('VITE_API_BASE_URL is not set in .env.local')
  return /^https?:\/\//i.test(raw) ? raw : `https://${raw}`
}

const rows = (schedule) =>
  Object.entries(schedule)
    .map(([id, v]) => ({
      id,
      category: v.category,
      item: v.subline,
      years: v.useful_life_years ?? null,
      mode: v.mode,
      how: MODE_LABEL[v.mode] ?? v.mode,
      flatPct: v.flat_pct ?? null,
      maxPct: v.max_pct ?? null,
      appraisal: Boolean(v.appraisal),
      note: v.note ?? null,
    }))
    .sort((a, b) => a.category.localeCompare(b.category) || a.item.localeCompare(b.item))

const csvCell = (s) => {
  const v = s === null || s === undefined ? '' : String(s)
  return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v
}

function toCsv(list) {
  const head = ['Category', 'Item', 'Useful life (years)', 'How it depreciates', 'Cap', 'Auto-priced', 'Note']
  const body = list.map((r) =>
    [
      r.category,
      r.item,
      r.years ?? '',
      r.how + (r.mode === 'flat_rate' && r.flatPct ? ` (${Math.round(r.flatPct * 100)}%)` : ''),
      r.maxPct ? `${Math.round(r.maxPct * 100)}%` : '',
      r.appraisal ? 'No — appraisal class' : 'Yes',
      r.note ?? '',
    ].map(csvCell).join(','),
  )
  return [head.join(','), ...body].join('\n') + '\n'
}

function toTs(list, categories) {
  const counts = {
    lines: list.length,
    categories: Object.keys(categories).length,
    appraisal: list.filter((r) => r.appraisal).length,
    noUsefulLife: list.filter((r) => r.years === null).length,
    capped: list.filter((r) => r.maxPct !== null).length,
  }
  return (
    '// GENERATED by scripts/build-depreciation-reference.mjs -- do not edit.\n' +
    '// Source of truth: GET /v1/depreciation-rules on the live backend.\n' +
    '// Refresh with: node scripts/build-depreciation-reference.mjs\n' +
    '// Verify with:  node scripts/build-depreciation-reference.mjs --check\n' +
    `// Captured: ${new Date().toISOString().slice(0, 10)}\n\n` +
    'export type ScheduleRefRow = {\n' +
    '  category: string\n  item: string\n  years: number | null\n  how: string\n' +
    '  flatPct: number | null\n  maxPct: number | null\n  appraisal: boolean\n  note: string | null\n}\n\n' +
    `export const SCHEDULE_COUNTS = ${JSON.stringify(counts, null, 2)} as const\n\n` +
    `export const SCHEDULE_CAPTURED = '${new Date().toISOString().slice(0, 10)}'\n\n` +
    'export const SCHEDULE_ROWS: ScheduleRefRow[] = ' +
    JSON.stringify(
      list.map(({ id: _id, mode: _mode, ...r }) => r),
      null,
      2,
    ) +
    '\n'
  )
}

const stamp = (s) => createHash('sha1').update(s.replace(/^\/\/ Captured: .*$/m, '')).digest('hex')

const origin = await base()
const res = await fetch(`${origin}/v1/depreciation-rules`)
if (!res.ok) throw new Error(`GET /v1/depreciation-rules -> ${res.status}`)
const data = await res.json()
if (!data?.schedule || !data?.schedule_categories) {
  throw new Error('response has no schedule / schedule_categories')
}

const list = rows(data.schedule)
const ts = toTs(list, data.schedule_categories)
const csv = toCsv(list)

if (check) {
  const [prevTs, prevCsv] = await Promise.all([
    readFile(TS_OUT, 'utf8').catch(() => ''),
    readFile(CSV_OUT, 'utf8').catch(() => ''),
  ])
  const stale = stamp(prevTs) !== stamp(ts) || prevCsv !== csv
  console.log(
    `depreciation reference: ${list.length} lines / ${Object.keys(data.schedule_categories).length} categories — ` +
      (stale ? 'STALE, re-run without --check' : 'up to date'),
  )
  process.exit(stale ? 1 : 0)
}

await writeFile(TS_OUT, ts, 'utf8')
await writeFile(CSV_OUT, csv, 'utf8')
console.log(
  `depreciation reference: ${list.length} lines / ${Object.keys(data.schedule_categories).length} categories written`,
)
